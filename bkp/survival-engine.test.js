'use strict';
const assert = require('node:assert/strict');
const {projectSurvival} = require('./survival-engine');
const base={corpus:12000,age:40,swp:1000,inflation:0,returns:0,endAge:42};
const start=new Date(2024,0,1);
const near=(actual,expected,tolerance=1e-6)=>assert.ok(Math.abs(actual-expected)<tolerance,`${actual} != ${expected}`);
let o=projectSurvival(base,start);
assert.equal(o.depleted,true);near(o.days,366);near(o.age,41);near(o.totalWithdrawn,12000);near(o.balance,0);
o=projectSurvival({...base,corpus:500},start);
near(o.days,15.5);near(o.totalWithdrawn,500);assert.equal(o.rows.length,1);
o=projectSurvival({...base,corpus:0},start);
assert.equal(o.days,0);assert.equal(o.depleted,true);assert.equal(o.age,40);
o=projectSurvival({...base,swp:0,returns:10},start);
near(o.balance,12000*1.1**2);assert.equal(o.depleted,false);assert.equal(o.days,731);
o=projectSurvival({...base,corpus:1e6,inflation:10},start);
near(o.rows[0].withdrawals,12000);near(o.rows[1].withdrawals,13200);near(o.balance,974800);
const ordinary=projectSurvival({...base,corpus:20000},start);
assert.ok(projectSurvival({...base,corpus:20000,inflation:10},start).days<ordinary.days);
assert.ok(projectSurvival({...base,corpus:20000,returns:-10},start).days<ordinary.days);
o=projectSurvival({...base,corpus:1e6,returns:8,inflation:6,endAge:100},new Date(2024,1,29));
for(const r of o.rows)near(r.opening+r.growth-r.withdrawals,r.balance,1e-5);
near(o.rows.reduce((s,r)=>s+r.days,0),o.days);assert.ok(o.rows.every(r=>r.balance>=0));
console.log('Passed: depletion, fractional days, leap years, zero corpus, compounding, inflation, losses, and cash-flow reconciliation.');
